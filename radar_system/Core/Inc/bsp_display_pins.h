#ifndef BSP_DISPLAY_PINS_H
#define BSP_DISPLAY_PINS_H

#include "bsp_display.h"
#include "stm32f103xb.h"

#if DISPLAY_CONFIG_DIGIT_COUNT != DISPLAY_CONFIG_THREE_DIGITS
#error "Radar FJ2352AH board has exactly three physical digits"
#endif

/* 来源：硬件项目正式引脚表V1.1；三位共阴，段选和NPN位选均高有效。 */
#define BSP_DISPLAY_SEGMENT_A_PIN GPIO_BSRR_BS11
#define BSP_DISPLAY_SEGMENT_B_PIN GPIO_BSRR_BS6
#define BSP_DISPLAY_SEGMENT_C_PIN GPIO_BSRR_BS0
#define BSP_DISPLAY_SEGMENT_D_PIN GPIO_BSRR_BS10
#define BSP_DISPLAY_SEGMENT_E_PIN GPIO_BSRR_BS12
#define BSP_DISPLAY_SEGMENT_F_PIN GPIO_BSRR_BS2
#define BSP_DISPLAY_SEGMENT_G_PIN GPIO_BSRR_BS7
#define BSP_DISPLAY_SEGMENT_DP_PIN GPIO_BSRR_BS1
#define BSP_DISPLAY_DIGIT_1_PIN GPIO_BSRR_BS8
#define BSP_DISPLAY_DIGIT_2_PIN GPIO_BSRR_BS9
#define BSP_DISPLAY_DIGIT_3_PIN GPIO_BSRR_BS10
#define BSP_DISPLAY_GPIOA_SEGMENT_MASK (BSP_DISPLAY_SEGMENT_B_PIN | BSP_DISPLAY_SEGMENT_G_PIN)
#define BSP_DISPLAY_GPIOB_SEGMENT_MASK (BSP_DISPLAY_SEGMENT_A_PIN | BSP_DISPLAY_SEGMENT_C_PIN | \
    BSP_DISPLAY_SEGMENT_D_PIN | BSP_DISPLAY_SEGMENT_E_PIN | BSP_DISPLAY_SEGMENT_F_PIN | BSP_DISPLAY_SEGMENT_DP_PIN)
#define BSP_DISPLAY_DIGIT_MASK (BSP_DISPLAY_DIGIT_1_PIN | BSP_DISPLAY_DIGIT_2_PIN | BSP_DISPLAY_DIGIT_3_PIN)

/* RM0008 Rev21第171、173页：每脚CRL/CRH字段配置为通用推挽2MHz，BSRR高半字复位。 */
#define BSP_DISPLAY_BSRR_RESET_SHIFT 16U
#define BSP_DISPLAY_GPIOA_CRL_MASK (GPIO_CRL_MODE6 | GPIO_CRL_CNF6 | GPIO_CRL_MODE7 | GPIO_CRL_CNF7)
#define BSP_DISPLAY_GPIOA_CRL_OUTPUT (GPIO_CRL_MODE6_1 | GPIO_CRL_MODE7_1)
#define BSP_DISPLAY_GPIOA_CRH_MASK (GPIO_CRH_MODE8 | GPIO_CRH_CNF8 | GPIO_CRH_MODE9 | \
    GPIO_CRH_CNF9 | GPIO_CRH_MODE10 | GPIO_CRH_CNF10)
#define BSP_DISPLAY_GPIOA_CRH_OUTPUT (GPIO_CRH_MODE8_1 | GPIO_CRH_MODE9_1 | GPIO_CRH_MODE10_1)
#define BSP_DISPLAY_GPIOB_CRL_MASK (GPIO_CRL_MODE0 | GPIO_CRL_CNF0 | GPIO_CRL_MODE1 | \
    GPIO_CRL_CNF1 | GPIO_CRL_MODE2 | GPIO_CRL_CNF2)
#define BSP_DISPLAY_GPIOB_CRL_OUTPUT (GPIO_CRL_MODE0_1 | GPIO_CRL_MODE1_1 | GPIO_CRL_MODE2_1)
#define BSP_DISPLAY_GPIOB_CRH_MASK (GPIO_CRH_MODE10 | GPIO_CRH_CNF10 | GPIO_CRH_MODE11 | \
    GPIO_CRH_CNF11 | GPIO_CRH_MODE12 | GPIO_CRH_CNF12)
#define BSP_DISPLAY_GPIOB_CRH_OUTPUT (GPIO_CRH_MODE10_1 | GPIO_CRH_MODE11_1 | GPIO_CRH_MODE12_1)
#define BSP_DISPLAY_CLOCK_MASK (RCC_APB2ENR_IOPAEN | RCC_APB2ENR_IOPBEN)

/* 字形位0～6为A～G，位7为DP；关闭字形不选通任何数码位。 */
#define BSP_DISPLAY_GLYPH_A_MASK (1U << 0U)
#define BSP_DISPLAY_GLYPH_B_MASK (1U << 1U)
#define BSP_DISPLAY_GLYPH_C_MASK (1U << 2U)
#define BSP_DISPLAY_GLYPH_D_MASK (1U << 3U)
#define BSP_DISPLAY_GLYPH_E_MASK (1U << 4U)
#define BSP_DISPLAY_GLYPH_F_MASK (1U << 5U)
#define BSP_DISPLAY_GLYPH_G_MASK (1U << 6U)
#define BSP_DISPLAY_GLYPH_BLANK 0U

#endif

#ifndef BSP_STARTUP_H
#define BSP_STARTUP_H
#include "bsp_board.h"

/* 启动轮询预算不依赖SysTick；等待次数上限，不表示精确的时间长度。 */
#define BSP_STARTUP_POLL_LIMIT 1000000UL
/* 正式表V1.1：PC4=C2门控、PC5=COMP_3；用户确认关闭残留USART1。 */
#define BSP_STARTUP_ENABLE_LEGACY_USART1 0
#define BSP_STARTUP_USART1_BAUDRATE 115200UL
#define BSP_STARTUP_USART1_BRR ((BSP_BOARD_PCLK1_HZ + BSP_STARTUP_USART1_BAUDRATE / 2UL) / BSP_STARTUP_USART1_BAUDRATE)
/* PC4/PC5模式字段每脚2位，AFR每脚4位；原配置为AF1、推挽、低速、无上下拉。 */
#define BSP_STARTUP_USART1_TX_PIN 4UL
#define BSP_STARTUP_USART1_RX_PIN 5UL
#define BSP_STARTUP_GPIO_MODE_WIDTH 2UL
#define BSP_STARTUP_GPIO_AF_WIDTH 4UL
#define BSP_STARTUP_GPIO_MODE_MASK 3UL
#define BSP_STARTUP_GPIO_AF_MASK 15UL
#define BSP_STARTUP_GPIO_MODE_AF 2UL
#define BSP_STARTUP_USART1_AF 1UL
#define BSP_STARTUP_USART1_PIN_MASK ((1UL << BSP_STARTUP_USART1_TX_PIN) | (1UL << BSP_STARTUP_USART1_RX_PIN))
#define BSP_STARTUP_USART1_MODE_MASK ((BSP_STARTUP_GPIO_MODE_MASK << (BSP_STARTUP_USART1_TX_PIN * BSP_STARTUP_GPIO_MODE_WIDTH)) | (BSP_STARTUP_GPIO_MODE_MASK << (BSP_STARTUP_USART1_RX_PIN * BSP_STARTUP_GPIO_MODE_WIDTH)))
#define BSP_STARTUP_USART1_MODE_BITS ((BSP_STARTUP_GPIO_MODE_AF << (BSP_STARTUP_USART1_TX_PIN * BSP_STARTUP_GPIO_MODE_WIDTH)) | (BSP_STARTUP_GPIO_MODE_AF << (BSP_STARTUP_USART1_RX_PIN * BSP_STARTUP_GPIO_MODE_WIDTH)))
#define BSP_STARTUP_USART1_AF_MASK ((BSP_STARTUP_GPIO_AF_MASK << (BSP_STARTUP_USART1_TX_PIN * BSP_STARTUP_GPIO_AF_WIDTH)) | (BSP_STARTUP_GPIO_AF_MASK << (BSP_STARTUP_USART1_RX_PIN * BSP_STARTUP_GPIO_AF_WIDTH)))
#define BSP_STARTUP_USART1_AF_BITS ((BSP_STARTUP_USART1_AF << (BSP_STARTUP_USART1_TX_PIN * BSP_STARTUP_GPIO_AF_WIDTH)) | (BSP_STARTUP_USART1_AF << (BSP_STARTUP_USART1_RX_PIN * BSP_STARTUP_GPIO_AF_WIDTH)))

/* STM32G071只有SW-DP：PA13/SWDIO、PA14/SWCLK使用AF0，禁止业务占用。
 * 下列芯片字段宏在bsp_startup.c加载官方stm32g0xx.h后使用。
 * RM0444 Rev6 7.5.3：GPIOA速度复位值0x0C000000，即PA13=11、PA14=00。 */
#define BSP_STARTUP_SWD_PIN_MASK (GPIO_OTYPER_OT13 | GPIO_OTYPER_OT14)
#define BSP_STARTUP_SWD_MODE_MASK (GPIO_MODER_MODE13 | GPIO_MODER_MODE14)
#define BSP_STARTUP_SWD_MODE_BITS (GPIO_MODER_MODE13_1 | GPIO_MODER_MODE14_1)
#define BSP_STARTUP_SWD_AF_MASK (GPIO_AFRH_AFSEL13 | GPIO_AFRH_AFSEL14)
#define BSP_STARTUP_SWD_AF_BITS 0UL /* 两脚AFR字段均为AF0。 */
#define BSP_STARTUP_SWD_PULL_MASK (GPIO_PUPDR_PUPD13 | GPIO_PUPDR_PUPD14)
#define BSP_STARTUP_SWD_PULL_BITS (GPIO_PUPDR_PUPD13_0 | GPIO_PUPDR_PUPD14_1)
#define BSP_STARTUP_SWD_SPEED_MASK (GPIO_OSPEEDR_OSPEED13 | GPIO_OSPEEDR_OSPEED14)
#define BSP_STARTUP_SWD_SPEED_BITS GPIO_OSPEEDR_OSPEED13

/** @brief 板级基础启动结果，不表示产品外设已经初始化。 */
typedef enum {
    BSP_STARTUP_OK = 0, /**< SWD、基础计时、时钟核对及已启用基础外设配置完成。 */
    BSP_STARTUP_BASE_FAILED = -1, /**< 独立SysTick基础计时初始化失败。 */
    BSP_STARTUP_CLOCK_FAILED = -2, /**< 电源/Flash/时钟等待失败或时钟核对不符。 */
    BSP_STARTUP_PERIPHERAL_FAILED = -3, /**< USART1收发使能确认失败。 */
    BSP_STARTUP_DEBUG_FAILED = -4 /**< GPIOA时钟或SWD两脚配置读回核对失败。 */
} BspStartupStatus;

/**
 * @brief 先显式配置SWD，再启动64MHz时钟、独立SysTick；默认不初始化残留USART1。
 * @return BSP_STARTUP_OK表示完成，其他枚举表示SWD、时钟、计时或串口初始化失败。
 */
BspStartupStatus BSP_Startup_Init(void);

/**
 * @brief 保留系统时钟配置接口，寄存器建立原HSI/PLL及总线分频。
 * @note 仅在调度器启动前使用；失败记录时钟故障并停止。
 */
void SystemClock_Config(void);

#endif

/**
 * @brief 初始化独占TIM1与所列GPIO，首次成功保持门控关闭和休眠；重复初始化不重置波形。
 * @return 成功DEV_OK，时钟、资源占用或配置读回异常DEV_IO_ERROR。
 */
DevStatus BSP_UltrasonicTx_Init(void);

/**
 * @brief 在任务或启动线程上下文唤醒至少2ms后，启动第1路反相连续PWM。
 * @return 成功DEV_OK，正在启动DEV_PENDING，未初始化或启动被取消DEV_NOT_READY，
 *         计时无进展DEV_TIMEOUT，上下文或外设配置异常DEV_IO_ERROR。
 * @note 线程中断屏蔽时轮询既有SysTick的COUNTFLAG，不主动开启中断或改动时基。
 */
DevStatus BSP_UltrasonicTx_StartContinuous(void);

/**
 * @brief 唤醒后发送一次有限周期脉冲串，TIM1最终更新中断关闭输出。
 * @param cycleCount 周期数，范围1至256。
 * @return 成功DEV_OK，参数错误DEV_ARGUMENT_ERROR，运行冲突DEV_PENDING，其余按连续启动契约。
 */
DevStatus BSP_UltrasonicTx_StartBurst(uint16_t cycleCount);

/** @brief 处理脉冲串最终更新并无等待关闭门控、输出及nSLEEP。 */
void TIM1_BRK_UP_TRG_COM_IRQHandler(void);

/**
 * @brief 先关闭全部门控，再关闭TIM1输出和nSLEEP；可在故障上下文调用，无等待。
 * @return 正常关闭DEV_OK，从未取得GPIO资源DEV_NOT_READY，资源时钟或关闭读回异常DEV_IO_ERROR。
 * @note 可清理初始化中途失败的资源，保留调用前中断屏蔽状态，不调用RTOS。
 */
DevStatus BSP_UltrasonicTx_Stop(void);


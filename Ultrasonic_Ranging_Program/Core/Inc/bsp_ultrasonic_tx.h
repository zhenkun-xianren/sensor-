/** @brief 最近一次TIM1结束中断的诊断记录；仅用于观察，不参与启停决策。 */
typedef struct {
    uint32_t irq_count; // 自上电累计TIM1结束IRQ次数，自然回绕。
    uint32_t last_irq_sr; // 关闭之前的TIM1状态标志，可检查UIF是否置位。
    uint32_t last_irq_cr1; // 关闭之前的TIM1控制值，可检查CEN和OPM。
    uint32_t last_irq_cnt; // 关闭之前的TIM1周期内计数值。
    uint32_t last_irq_rcr; // 关闭之前的TIM1重复计数配置，应为周期数减一。
    uint32_t last_irq_cycle_count; // 该次中断对应的软件请求周期数。
    uint32_t last_irq_tim3_us; // 配置匹配时的TIM3计数，当前测距中作为发射起点后的IRQ参考us。
    uint32_t update_wait_failed_count; // UG等待或清除/配置核对失败的累计次数。
    bool tim3_time_valid; // TIM3时钟、1MHz计数及同步触发配置匹配且正在运行。
} BspUltrasonicTxDebug;

/** @brief Watch可观察的结束IRQ快照；须结合irq_count确认新旧，外部不得修改。 */
extern volatile BspUltrasonicTxDebug g_bsp_ultrasonic_tx_debug;


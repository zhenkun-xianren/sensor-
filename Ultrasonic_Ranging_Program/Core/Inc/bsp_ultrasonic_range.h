#define BSP_ULTRASONIC_RANGE_TIMER_SELECTION TIM_TISEL_TI2SEL_0 // RM0444：TI2SEL=0001为COMP2。
#define BSP_ULTRASONIC_RANGE_CAPTURE_CCR CCR2

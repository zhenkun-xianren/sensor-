/** @brief 门控动作的软件读回诊断；IDR仅为采样值，不代替U7实物功能测试。 */
typedef struct {
    uint32_t open_count; /**< 累计开门成功次数，自然回绕。 */
    uint32_t close_count; /**< Init/每轮开始/结束关门成功次数，不含TX模块独立关门。 */
    uint32_t open_readback_failed_count; /**< 开门ODR、模式或捕获配置读回失败次数。 */
    uint32_t close_readback_failed_count; /**< 关门ODR或模式读回失败次数。 */
    uint32_t tx_not_stopped_count; /**< 开门前发现发射仍未完全关闭的次数。 */
    uint32_t last_open_us; /**< 最近开门写GPIO后TIM3时间，单位us。 */
    uint32_t last_close_us; /**< 最近关门时TIM3时间，Init为零。 */
    uint32_t open_odr; /**< 最近开门尝试后的选中GPIO ODR完整快照。 */
    uint32_t open_idr; /**< 最近开门尝试后的GPIO IDR快照，瞬时采样。 */
    uint32_t close_odr; /**< 最近关门尝试后的选中GPIO ODR完整快照。 */
    uint32_t close_idr; /**< 最近关门尝试后的GPIO IDR快照，瞬时采样。 */
    uint32_t tx_irq_count_before_start; /**< 本轮开始时TX结束中断累计数。 */
    uint32_t tx_irq_count_at_open; /**< 最近开门尝试时TX结束中断累计数。 */
    uint32_t tx_end_us_at_open; /**< 最近开门尝试时TX结束IRQ时间快照，单位us。 */
    bool tx_end_time_valid_at_open; /**< 对应TX结束时间是否通过既有时基检查。 */
    uint32_t minimum_echo_us; /**< 按下限/声速/偏置推导的最早回波时间，当前往返2916us；只接收不使用。 */
} BspUltrasonicRangeGateDebug;

/** @brief Watch只读门控诊断；运行时不要修改，快照字段须结合次数判断新旧。 */
extern volatile BspUltrasonicRangeGateDebug g_bsp_ultrasonic_range_gate_debug;

/** @brief 配置接收资源，成功保持钳位和发射停止。
 * @param config 非空、范围合法的设备配置。
 * @return 成功DEV_OK，参数错误DEV_ARGUMENT_ERROR，资源或读回失败DEV_IO_ERROR。 */
DevStatus BSP_UltrasonicRange_Init(const DevUltrasonicRangeConfig *config);

/** @brief 按配置开始发射测距或内部时钟持续只接收；须在中断开启的线程调用。
 * @return 开始DEV_OK，正在测量DEV_PENDING，未初始化或取消DEV_NOT_READY，其他为启动原错误。 */
DevStatus BSP_UltrasonicRange_StartMeasurement(void);

/** @brief 在短临界区复制原始测距结果或持续接收诊断；距离计算由Port执行。
 * @param result 非空结果对象。
 * @return 完成DEV_OK，进行中DEV_PENDING，参数错误DEV_ARGUMENT_ERROR，未初始化DEV_NOT_READY。 */
DevStatus BSP_UltrasonicRange_ReadResult(DevUltrasonicRangeResult *result);

/** @brief 无等待关闭发射、取消捕获并恢复全部接收钳位；故障上下文可调用。
 * @return 成功DEV_OK，从未取得接收资源DEV_NOT_READY，关闭读回失败DEV_IO_ERROR。 */
DevStatus BSP_UltrasonicRange_Stop(void);

/** @brief 按模式处理测距窗口或持续接收计数，记录资格及覆盖/回绕。 */
void TIM3_IRQHandler(void);


#define BSP_ULTRASONIC_RANGE_TIMER_RECEIVE_IRQS (TIM_DIER_CC1IE | TIM_DIER_UIE)
/* TIM3 SR有效rc_w0位写1保持，待清位写0；保留位保持复位值。 */
#define BSP_ULTRASONIC_RANGE_STATUS_MASK (TIM_SR_UIF | TIM_SR_CC1IF | TIM_SR_CC2IF | TIM_SR_CC3IF | TIM_SR_CC4IF | TIM_SR_TIF | TIM_SR_CC1OF | TIM_SR_CC2OF | TIM_SR_CC3OF | TIM_SR_CC4OF)

/** @brief 配置接收资源，成功保持钳位和发射停止。
 * @param config 非空、范围合法的设备配置。
 * @return 成功DEV_OK，参数错误DEV_ARGUMENT_ERROR，资源或读回失败DEV_IO_ERROR。 */
DevStatus BSP_UltrasonicRange_Init(const DevUltrasonicRangeConfig *config);

/** @brief 按配置开始发射测距或内部时钟持续只接收；须在中断开启的线程调用。
 * @return 开始DEV_OK，正在测量DEV_PENDING，未初始化或取消DEV_NOT_READY，其他为启动原错误。 */
DevStatus BSP_UltrasonicRange_StartMeasurement(void);

/** @brief 在短临界区复制原始测距结果或持续接收诊断；距离计算由Port执行。
 * @param result 非空结果对象。
 * @return 完成DEV_OK，进行中DEV_PENDING，参数错误DEV_ARGUMENT_ERROR，未初始化DEV_NOT_READY。 */
DevStatus BSP_UltrasonicRange_ReadResult(DevUltrasonicRangeResult *result);

/** @brief 无等待关闭发射、取消捕获并恢复全部接收钳位；故障上下文可调用。
 * @return 成功DEV_OK，从未取得接收资源DEV_NOT_READY，关闭读回失败DEV_IO_ERROR。 */
DevStatus BSP_UltrasonicRange_Stop(void);

/** @brief 按模式处理测距窗口或持续接收计数，记录资格及覆盖/回绕。 */
void TIM3_IRQHandler(void);


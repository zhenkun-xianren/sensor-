#define BSP_ULTRASONIC_RANGE_INTERRUPTS_ENABLED 0UL
#define BSP_ULTRASONIC_RANGE_UPDATE_POLL_LIMIT 1024UL // TIM3软件更新完成的有限轮询上限。

#define BSP_ULTRASONIC_RANGE_GPIO_CLOCKS (RCC_IOPENR_GPIOAEN | RCC_IOPENR_GPIOBEN | RCC_IOPENR_GPIOCEN)
#define BSP_ULTRASONIC_RANGE_A_CLAMP_MASK (GPIO_ODR_OD4 | GPIO_ODR_OD9)
#define BSP_ULTRASONIC_RANGE_A_CLAMP_ON (GPIO_BSRR_BS4 | GPIO_BSRR_BS9)
#define BSP_ULTRASONIC_RANGE_B_CLAMP_MASK GPIO_ODR_OD12
#define BSP_ULTRASONIC_RANGE_B_CLAMP_ON GPIO_BSRR_BS12
#define BSP_ULTRASONIC_RANGE_C_CLAMP_MASK GPIO_ODR_OD3

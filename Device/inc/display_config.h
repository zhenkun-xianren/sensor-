#ifndef DISPLAY_CONFIG_H
#define DISPLAY_CONFIG_H

/* 所有编译单元须使用相同配置；工程宏可覆盖默认四位，库原有调用默认不变。 */
#define DISPLAY_CONFIG_THREE_DIGITS 3U
#define DISPLAY_CONFIG_FOUR_DIGITS 4U
#ifndef DISPLAY_CONFIG_DIGIT_COUNT
#define DISPLAY_CONFIG_DIGIT_COUNT DISPLAY_CONFIG_FOUR_DIGITS
#endif

#if DISPLAY_CONFIG_DIGIT_COUNT == DISPLAY_CONFIG_THREE_DIGITS
#define DISPLAY_CONFIG_MAX_VALUE 999U
#elif DISPLAY_CONFIG_DIGIT_COUNT == DISPLAY_CONFIG_FOUR_DIGITS
#define DISPLAY_CONFIG_MAX_VALUE 9999U
#else
#error "DISPLAY_CONFIG_DIGIT_COUNT must be 3 or 4"
#endif

/* 始终保留至少一位整数，小数位上限按物理位数推导。 */
#define DISPLAY_CONFIG_MAX_DECIMAL_PLACES (DISPLAY_CONFIG_DIGIT_COUNT - 1U)

#endif

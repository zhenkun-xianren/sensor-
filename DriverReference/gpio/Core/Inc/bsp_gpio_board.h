#ifndef BSP_GPIO_BOARD_H
#define BSP_GPIO_BOARD_H
#include "bsp_gpio.h"
#include "stm32f103xb.h"

/* RM0008 Rev21：CNF=00、MODE=10表示2MHz通用推挽输出。
 * 使用官方CMSIS字段，只改PA1/PA5/PA6及PB14/PB15。 */
#define BSP_GPIO_RELAY_MASK GPIO_ODR_ODR5
#define BSP_GPIO_OPTO_MASK GPIO_ODR_ODR1
#define BSP_GPIO_BUZZER_MASK GPIO_ODR_ODR6
#define BSP_GPIO_WARNING_MASK GPIO_ODR_ODR15
#define BSP_GPIO_POWER_MASK GPIO_ODR_ODR14
#define BSP_GPIO_A_MASK (BSP_GPIO_RELAY_MASK | BSP_GPIO_OPTO_MASK | BSP_GPIO_BUZZER_MASK)
#define BSP_GPIO_B_MASK (BSP_GPIO_WARNING_MASK | BSP_GPIO_POWER_MASK)
#define BSP_GPIO_A_FIELDS (GPIO_CRL_MODE1 | GPIO_CRL_CNF1 | GPIO_CRL_MODE5 | GPIO_CRL_CNF5 | GPIO_CRL_MODE6 | GPIO_CRL_CNF6)
#define BSP_GPIO_B_FIELDS (GPIO_CRH_MODE14 | GPIO_CRH_CNF14 | GPIO_CRH_MODE15 | GPIO_CRH_CNF15)
#define BSP_GPIO_A_MODES (GPIO_CRL_MODE1_1 | GPIO_CRL_MODE5_1 | GPIO_CRL_MODE6_1)
#define BSP_GPIO_B_MODES (GPIO_CRH_MODE14_1 | GPIO_CRH_MODE15_1)
#define BSP_GPIO_A_HIGH ((BSP_GPIO_RELAY_OFF << BSP_GPIO_RELAY_PIN) | (BSP_GPIO_OPTO_OFF << BSP_GPIO_OPTO_PIN) | (BSP_GPIO_BUZZER_OFF << BSP_GPIO_BUZZER_PIN))
#define BSP_GPIO_B_HIGH ((BSP_GPIO_WARNING_OFF << BSP_GPIO_WARNING_PIN) | (BSP_GPIO_POWER_OFF << BSP_GPIO_POWER_PIN))
#define BSP_GPIO_BSRR_RESET_SHIFT GPIO_BSRR_BR0_Pos
#define BSP_GPIO_CLOCKS (RCC_APB2ENR_IOPAEN | RCC_APB2ENR_IOPBEN)
#endif

#ifndef BSP_DISPLAY_STM32F1_PINS_H
#define BSP_DISPLAY_STM32F1_PINS_H

#include <stdint.h>
#include "bsp_display.h"

/* 以下引脚对应当前甲烷传感器板；移植到其他板卡时在本文件修改。 */
#define BSP_DISPLAY_STM32F1_DIGIT_1_PIN 11U
#define BSP_DISPLAY_STM32F1_DIGIT_2_PIN 10U
#define BSP_DISPLAY_STM32F1_DIGIT_3_PIN 9U
#define BSP_DISPLAY_STM32F1_DIGIT_4_PIN 12U
#define BSP_DISPLAY_STM32F1_DP_PIN 15U

#define BSP_DISPLAY_STM32F1_SEGMENT_A_PIN 9U
#define BSP_DISPLAY_STM32F1_SEGMENT_B_PIN 8U
#define BSP_DISPLAY_STM32F1_SEGMENT_C_PIN 7U
#define BSP_DISPLAY_STM32F1_SEGMENT_D_PIN 6U
#define BSP_DISPLAY_STM32F1_SEGMENT_E_PIN 5U
#define BSP_DISPLAY_STM32F1_SEGMENT_F_PIN 4U
#define BSP_DISPLAY_STM32F1_SEGMENT_G_PIN 3U

#define BSP_DISPLAY_STM32F1_BSRR_RESET_SHIFT 16U
#define BSP_DISPLAY_STM32F1_DIGIT_INDEX_MASK (BSP_DISPLAY_DIGIT_COUNT - 1U)
#define BSP_DISPLAY_STM32F1_DIGIT_PIN_MASK \
    ((1UL << BSP_DISPLAY_STM32F1_DIGIT_1_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_DIGIT_2_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_DIGIT_3_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_DIGIT_4_PIN))
#define BSP_DISPLAY_STM32F1_DP_PIN_MASK (1UL << BSP_DISPLAY_STM32F1_DP_PIN)
#define BSP_DISPLAY_STM32F1_SEGMENT_PIN_MASK \
    ((1UL << BSP_DISPLAY_STM32F1_SEGMENT_A_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_SEGMENT_B_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_SEGMENT_C_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_SEGMENT_D_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_SEGMENT_E_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_SEGMENT_F_PIN) | \
     (1UL << BSP_DISPLAY_STM32F1_SEGMENT_G_PIN))

#endif
